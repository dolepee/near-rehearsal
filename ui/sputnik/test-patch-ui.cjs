'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const here = __dirname;
const html = fs.readFileSync(path.join(here, 'public/patch.html'), 'utf8');
const js = fs.readFileSync(path.join(here, 'public/patch.js'), 'utf8');
const route = fs.readFileSync(path.join(here, 'patch-route.cjs'), 'utf8');

assert.match(html, /id="patch-outcomes"/);
assert.match(html, /id="patch-failed"/);
assert.match(html, /id="recent-runs"/);
assert.ok(html.indexOf('id="patch-outcomes"') < html.indexOf('id="patch-report"'), 'measured outcomes precede raw Markdown');
assert.match(html, /literal|Source diff|textarea/i);
assert.match(js, /Download evidence package/);
assert.match(html, /Recent patch checks/);
assert.match(js, /api\/patch\/runs/);
assert.match(js, /Not available/);
assert.match(js, /Not measured/);
assert.match(js, /value\(s\.retry\?\.gross\)/);
assert.doesNotMatch(js, /retry\?\.gross,\s*'0 NEAR'/);
assert.match(js, /First recovery gas/);
assert.match(js, /proposerNet/);
assert.match(js, /Retry gas/);
assert.match(js, /Retry proposer net/);
assert.match(js, /mine !== view/);
assert.match(js, /sessionStorage\.setItem\(runKey, runId\)/);
assert.match(js, /All defined checks passed/);
assert.match(js, /failed/);
assert.match(route, /review-package/);
assert.match(route, /not the older `repair:review` bundle format/);
assert.match(route, /interrupted|restarted/i);
assert.match(route, /No completed checker report/);
console.log('patch UI: outcomes before raw Markdown, honest unavailable values, recent runs, package and interrupted copy present');
